VALID_SUPERFICIES = {"app", "CLI", "extension", "codex-web", "iOS"}
VALID_AREAS = {"windows-os", "sandbox", "app-server", "connectivity", "TUI", "session",
               "rate-limits", "tool-calls", "browser", "remote", "model-behavior",
               "performance", "mcp", "auth", "context", "subagent", "config", "computer-use"}


def main():
    rows = [json.loads(l) for l in open(SRC) if l.strip()]
    src_ids = [r["id"] for r in rows]
    assert len(src_ids) == len(set(src_ids)), "ids duplicados en la entrada"

    missing = [i for i in src_ids if i not in C]
    extra = [i for i in C if i not in src_ids]
    assert not missing, f"sin clasificar: {missing}"
    assert not extra, f"ids desconocidos: {extra}"

    for i, (t, s, a) in C.items():
        assert t in VALID_TIPOS, (i, t)
        assert s in VALID_SUPERFICIES, (i, s)
        for x in a:
            assert x in VALID_AREAS, (i, x)
        assert len(set(a)) == len(a), (i, a)

    with open(DST, "w") as f:
        for r in rows:
            t, s, a = C[r["id"]]
            f.write(json.dumps({
                "id": r["id"],
                "titulo": r["titulo"],
                "tipo": t,
                "superficie": s,
                "areas": a,
            }, ensure_ascii=False) + "\n")

    print(f"OK: {len(rows)} incidencias clasificadas -> {DST}")



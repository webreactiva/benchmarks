VALID_AREAS = {
    "windows-os", "sandbox", "app-server", "connectivity", "TUI", "session",
    "rate-limits", "tool-calls", "browser", "remote", "model-behavior",
    "performance", "mcp", "auth", "context", "subagent", "config", "computer-use",
}
VALID_TIPOS = {"bug", "enhancement", "documentation"}
VALID_SUPERFICIES = {"app", "CLI", "extension", "codex-web", "iOS"}


def main():
    rows = []
    with open("incidencias.jsonl", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))

    if len(rows) != len(C):
        sys.exit(f"cobertura incompleta: {len(rows)} incidencias, {len(C)} clasificadas")

    out = []
    for idx, inc in enumerate(rows, start=1):
        tipo, sup, areas = C[idx]
        assert tipo in VALID_TIPOS, (idx, tipo)
        assert sup in VALID_SUPERFICIES, (idx, sup)
        assert set(areas) <= VALID_AREAS, (idx, areas)
        assert areas == sorted(set(areas), key=areas.index), (idx, areas)
        out.append({
            "id": inc["id"],
            "tipo": tipo,
            "superficie": sup,
            "areas": areas,
        })

    with open("clasificacion.jsonl", "w", encoding="utf-8") as fh:
        for rec in out:
            fh.write(json.dumps(rec, ensure_ascii=False) + "\n")
    print(f"escritas {len(out)} lineas en clasificacion.jsonl")


if __name__ == "__main__":
    main()
